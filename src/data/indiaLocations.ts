export function getCitiesForState(stateName: string): LocationCity[] {
  if (!stateName) return MAJOR_INDIAN_CITIES;
  const filtered = MAJOR_INDIAN_CITIES.filter(
    (c) => c.state.toLowerCase() === stateName.trim().toLowerCase()
  );
  return filtered.length > 0 ? filtered : MAJOR_INDIAN_CITIES;
}
